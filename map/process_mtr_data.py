def parse_mtr_data():
    reader = csv.DictReader(io.StringIO(mtr_csv_text.strip()))
    stations = []
    for row in reader:
        c_name = row['站名(中文)'].strip()
        e_name = row['站名(英文)'].strip()
        lat = float(row['纬度'])
        lng = float(row['经度'])
        lines = row['线路'].strip()
        
        # 提取主色调
        main_line = lines.split('/')[0]
        color = LINE_COLORS.get(main_line, "#007dc5")
        
        stations.append({
            "id": f"mtr_{e_name.lower().replace(' ', '_').replace('.', '')}",
            "category": "mtr",
            "name": f"{c_name}站 ({lines})",
            "station_name_cn": c_name,
            "station_name_en": e_name,
            "lines": lines,
            "main_line": main_line,
            "color": color,
            "lat": lat,
            "lng": lng
        })
    return stations

def parse_project_mtr_data():
    reader = csv.DictReader(io.StringIO(project_mtr_csv_text.strip()))
    proj_map = {}
    for row in reader:
        p_name = row['楼盘名称'].strip()
        proj_map[p_name] = {
            "address": row['详细地址'].strip(),
            "nearest_mtr_cn": row['最近港铁站(中文)'].strip(),
            "nearest_mtr_en": row['最近港铁站(英文)'].strip(),
            "nearest_mtr_lines": row['港铁线路'].strip(),
            "nearest_mtr_lat": float(row['港铁站纬度']),
            "nearest_mtr_lng": float(row['港铁站经度']),
            "dist_straight_m": int(float(row['直线距离(米)'])),
            "dist_walk_m": int(float(row['估算步行距离(米)'])),
            "walk_time_min": float(row['估算步行时间(分钟)'])
        }
    return proj_map

def update_files():
    base_dir = "/Users/nb/google/Antigravity/工作/运营/价单/sandbox"
    
    stations = parse_mtr_data()
    proj_mtr_map = parse_project_mtr_data()
    
